putsprite:
           ld a,(ix)
           ld b,a
           inc ix
putsprite_loop:
           push bc
           push hl

            ld de,(tasptr)
            call vpoke
            inc de
            inc de
            inc de
            inc de
            ld (tasptr),de

            ld a,(ix)
            add a,l
            dec a
            out (#98),a
            ld a,(ix+1)
            add a,h
            call c,setoutofscreen
            out (#98),a
            ld a,(tascntr)
            nop
            out (#98),a
            add a,4
            ld (tascntr),a
            ld a,(ix+2)
            out (#98),a
            ld de,(tgsptr)
            call vpoke
            ld hl,32
            add hl,de
            ld (tgsptr),hl

            ld l,(ix+3)
            ld h,(ix+4)
            ld c,#98
            ld b,32
            call slowotir

            ld bc,5
            add ix,bc
            pop hl
            pop bc
            djnz putsprite_loop
            ld de,(tasptr)
            call vpoke

            ld a,(current_mode)
            cp 1
            ret z

            ld a,208
            out (#98),a

            ret

